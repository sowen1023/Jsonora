export type Translate = (key: Key, vars?: Record<string, string | number>) => string

export function getTranslator(locale: Locale): Translate {
  const dictionary = locale === 'en' ? en : zh
  return (key, vars) => {
    let text = dictionary[key]
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.replaceAll(`{${name}}`, String(value))
      }
    }
    return text
  }
}

const I18nContext = createContext<Locale>('zh')

export function I18nProvider(props: { locale: Locale; children: ComponentChildren }) {
  return <I18nContext.Provider value={props.locale}>{props.children}</I18nContext.Provider>
}

export function useI18n(): { locale: Locale; t: Translate } {
  const locale = useContext(I18nContext)
  return { locale, t: getTranslator(locale) }
}

export function localizedTypeLabel(kind: JsonKind, t: Translate): string {
  const keys: Record<JsonKind, Key> = {
    object: 'typeObject', array: 'typeArray', string: 'typeString', number: 'typeNumber',
    boolean: 'typeBoolean', null: 'typeNull',
  }
  return t(keys[kind])
}
